<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Выделение слова в заголовке звёздочками: «Стратегия *развития* региона».
 *
 * Приём выбран вместо отдельной колонки «какие слова красить» намеренно:
 * колонка хранила бы номера слов и разъезжалась с текстом при первой же
 * правке заголовка, да ещё и отдельно на каждом языке. Разметка живёт внутри
 * самой строки — переводчик переносит звёздочки туда, где в его языке стоит
 * нужное слово, и ничего синхронизировать не нужно.
 *
 * Заголовок остаётся простым текстом: HTML внутрь не допускается, звёздочки
 * разбираются УЖЕ ПОСЛЕ экранирования. Поэтому `<b>` в заголовке по-прежнему
 * виден как текст, а не как разметка, и правило «поля-заголовки не принимают
 * HTML» не нарушено.
 *
 * Где HTML недопустим (title=, alt=, <title>, meta, пост в Telegram, поисковый
 * индекс) — зовите plain(): она снимает звёздочки, ничего не добавляя.
 */
final class TitleMarkup
{
    /**
     * Пара звёздочек вокруг непустого куска строки без переноса.
     *
     * Пробел сразу после открывающей (и перед закрывающей) не считается
     * разметкой: в тексте «5 * 3 = 15 * 5» звёздочки — знак умножения, и
     * красить середину выражения нельзя. Ограничение длины отсекает случай,
     * когда одинокая звёздочка в начале строки «съедает» весь заголовок до
     * следующей.
     */
    private const PATTERN = '/\*(?!\s)([^*\n]{1,200}?)(?<!\s)\*/u';

    /** Экранированный заголовок, где *слово* превращено в акцентный span. */
    public static function html(?string $text): string
    {
        $escaped = htmlspecialchars((string) $text, ENT_QUOTES);

        // Экранирование звёздочек не производит, поэтому разбор безопасен:
        // разметка не может приехать из самого текста.
        return (string) preg_replace(
            self::PATTERN,
            '<span class="tx-mark">$1</span>',
            $escaped
        );
    }

    /** Тот же заголовок без звёздочек и без разметки — для атрибутов и SEO. */
    public static function plain(?string $text): string
    {
        return (string) preg_replace(self::PATTERN, '$1', (string) $text);
    }

    /** Есть ли в строке выделение (нужно шаблонам, решающим, звать ли html()). */
    public static function has(?string $text): bool
    {
        return preg_match(self::PATTERN, (string) $text) === 1;
    }
}
